import esbuild from "esbuild";
import process from "process";
import builtins from "builtin-modules";
import { readFileSync, writeFileSync } from "fs";

const prod = process.argv[2] === "production";
const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
If you want to view the source, please visit the GitHub repository of this plugin.
*/`;

function prefixCss(css, prefix) {
  const source = css.replace(/\/\*[\s\S]*?\*\//g, "");
  let out = "";
  let index = 0;
  const length = source.length;
  const matchingBrace = (start) => {
    let depth = 0;
    for (let cursor = start; cursor < length; cursor++) {
      if (source[cursor] === "{") depth++;
      else if (source[cursor] === "}") {
        depth--;
        if (depth === 0) return cursor;
      }
    }
    return length - 1;
  };
  while (index < length) {
    while (index < length && /\s/.test(source[index])) {
      out += source[index];
      index++;
    }
    if (index >= length) break;
    if (source.startsWith("@media", index) || source.startsWith("@supports", index)) {
      const brace = source.indexOf("{", index);
      const end = matchingBrace(brace);
      out += `${source.slice(index, brace + 1)}${prefixCss(source.slice(brace + 1, end), prefix)}}`;
      index = end + 1;
      continue;
    }
    if (source[index] === "@") {
      const brace = source.indexOf("{", index);
      if (brace < 0) {
        out += source.slice(index);
        break;
      }
      const end = matchingBrace(brace);
      out += source.slice(index, end + 1);
      index = end + 1;
      continue;
    }
    const brace = source.indexOf("{", index);
    if (brace < 0) {
      out += source.slice(index);
      break;
    }
    const end = matchingBrace(brace);
    const selector = source.slice(index, brace).trim();
    const body = source.slice(brace + 1, end);
    const prefixed = selector
      .split(",")
      .map((part) => {
        const trimmed = part.trim();
        if (!trimmed || trimmed.startsWith(prefix)) return trimmed;
        return `${prefix} ${trimmed}`;
      })
      .join(",\n");
    out += `${prefixed} {${body}}`;
    index = end + 1;
  }
  return out;
}

function writeStyles() {
  const vendor = [
    "node_modules/codemirror/lib/codemirror.css",
    "node_modules/codemirror/addon/dialog/dialog.css",
    "node_modules/codemirror/addon/fold/foldgutter.css",
  ]
    .map((file) => readFileSync(file, "utf8"))
    .join("\n");
  const app = readFileSync("src/styles.css", "utf8");
  const css = `/* Generated by esbuild.config.mjs. Edit src/styles.css. */\n${prefixCss(vendor, ".obsidi-format")}\n${app}\n`;
  writeFileSync("styles.css", css);
}

const context = await esbuild.context({
  banner: { js: banner },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtins,
  ],
  format: "cjs",
  target: "es2020",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
  minify: prod,
  legalComments: "inline",
  plugins: [
    {
      name: "obsidiformat-styles",
      setup(build) {
        build.onStart(() => writeStyles());
      },
    },
  ],
});

if (prod) {
  await context.rebuild();
  process.exit(0);
} else {
  await context.watch();
}
